package main

import (
	"os"
	"path/filepath"
	"strings"
	"testing"
)

// write creates a file under dir, making its parents.
func write(t *testing.T, dir, name, body string) {
	t.Helper()
	p := filepath.Join(dir, name)
	if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(p, []byte(body), 0o644); err != nil {
		t.Fatal(err)
	}
}

func TestCheck(t *testing.T) {
	t.Parallel()
	dir := t.TempDir()
	write(t, dir, "ok/ok.go", "// Package ok is documented.\npackage ok\n\n// F does nothing.\nfunc F() {}\n")
	write(t, dir, "bad/bad.go", "package bad\n\nfunc f() {}\n\ntype T struct{}\n\nfunc (T) M() {}\n")
	write(t, dir, "bad/bad_test.go", "package bad\n\nfunc helper() {}\n")
	write(t, dir, "gen/gen.go", "// Code generated by x. DO NOT EDIT.\n\npackage gen\n\nfunc g() {}\n")
	write(t, dir, "ok/testdata/x.go", "package x\n\nfunc h() {}\n")

	var out strings.Builder
	n, err := check(&out, []string{dir + "/..."})
	if err != nil {
		t.Fatal(err)
	}
	got := out.String()
	for _, want := range []string{"f has no doc comment", "M has no doc comment", "bad: package has no package comment"} {
		if !strings.Contains(got, want) {
			t.Errorf("output lacks %q:\n%s", want, got)
		}
	}
	for _, unwanted := range []string{"helper", "g has", "h has", "ok: package"} {
		if strings.Contains(got, unwanted) {
			t.Errorf("output has %q (tests, generated files and testdata are skipped):\n%s", unwanted, got)
		}
	}
	if n != 3 {
		t.Errorf("found %d problems, want 3", n)
	}

	// Without /... only the named directory is checked.
	if n, err := check(&out, []string{dir}); err != nil || n != 0 {
		t.Errorf("check(%s) = %d, %v; want 0, nil", dir, n, err)
	}
}

func TestCheckErrors(t *testing.T) {
	t.Parallel()
	if _, err := check(&strings.Builder{}, []string{filepath.Join(t.TempDir(), "missing") + "/..."}); err == nil {
		t.Error("a missing directory isn't an error")
	}
	dir := t.TempDir()
	write(t, dir, "broken.go", "package broken\nfunc (")
	if _, err := check(&strings.Builder{}, []string{dir}); err == nil {
		t.Error("a file that doesn't parse isn't an error")
	}
}
